"""Build the rolling PowerShell entrypoint from the verified, public release ZIP."""
import argparse
import base64
import hashlib
import json
from pathlib import Path
import textwrap

ROOT = Path(__file__).resolve().parents[1]
TEMPLATE = """# JJ AI TECH | Windows | Self-contained public release. Generated by tools/build_windows_entry.py.
& {
    $ErrorActionPreference = 'Stop'
    if (@(Get-ExecutionPolicy -List | Where-Object { $_.ExecutionPolicy -in @('AllSigned','Restricted') }).Count) {
        throw 'IT signing policy restricts this installer'
    }
    $archive = @'
__ARCHIVE__
'@
    $bytes = [Convert]::FromBase64String($archive)
    $sha = [Security.Cryptography.SHA256]::Create()
    try { $hash = [BitConverter]::ToString($sha.ComputeHash($bytes)).Replace('-','').ToLowerInvariant() } finally { $sha.Dispose() }
    if ($hash -ne '__SHA__') { throw 'Package checksum mismatch; nothing installed.' }
    $dir = Join-Path $env:TEMP ('jjaitech-install-' + [guid]::NewGuid().ToString('N'))
    New-Item -ItemType Directory -Path $dir | Out-Null
    $previous = $env:CODEBUDDY_FORCE_LITE_WB_BUNDLE
    try {
        # WorkBuddy 5.9.3 ships only its lite-wb CLI bundle. This scope ends with this install.
        $env:CODEBUDDY_FORCE_LITE_WB_BUNDLE = '1'
        $zip = Join-Path $dir 'release.zip'
        [IO.File]::WriteAllBytes($zip, $bytes)
        Expand-Archive -LiteralPath $zip -DestinationPath $dir
        $bootstrap = Join-Path $dir 'jjaitech-memory/distribution/bootstrap-windows.ps1'
        & ([scriptblock]::Create([IO.File]::ReadAllText($bootstrap))) -PackageRoot $dir
    } finally {
        $env:CODEBUDDY_FORCE_LITE_WB_BUNDLE = $previous
        Remove-Item -LiteralPath $dir -Recurse -Force -ErrorAction SilentlyContinue
    }
}
"""

def render(archive):
    manifest = json.loads((ROOT / 'release.json').read_text(encoding='utf-8'))
    data = archive.read_bytes()
    if hashlib.sha256(data).hexdigest() != manifest['sha256']:
        raise ValueError('Input is not the approved release ZIP')
    body = '\n'.join(textwrap.wrap(base64.b64encode(data).decode('ascii'), 120))
    return TEMPLATE.replace('__ARCHIVE__', body).replace('__SHA__', manifest['sha256'])

if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('release_zip', type=Path)
    args = parser.parse_args()
    (ROOT / 'install.ps1').write_bytes(render(args.release_zip).encode('ascii'))
